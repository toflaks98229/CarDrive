        /// 나눠서 대입하면 몇 프레임에 걸쳐 서서히 바뀌는데, 오히려 전환이 덜 보입니다.
        /// </summary>
        [Tooltip("단계가 바뀔 때 한 프레임에 값을 대입할 타일 수. 나눠 대입해야 그 프레임이 늘어지지 않습니다.")]
        [Range(1, 16)]
        public int maxDetailLodApplicationsPerFrame = 3;


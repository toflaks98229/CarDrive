using System.Collections.Generic;
using UnityEngine;

namespace CarDrive.Systems
{
    /// <summary>
    /// 월드의 겉모습과 풀에 관한 값을 한곳에 모아 둔 설정입니다.
    ///
    /// 이 값들은 원래 도구마다 <c>private const</c> 로 흩어져 있었습니다.
    /// 룩을 이것저것 시험하는 동안에는 그래도 됐지만, 방향이 정해진 지금은
    /// <b>값을 만지려고 코드를 열어야 하는 것</b>이 불편할 뿐입니다.
    ///
    /// 런타임 어셈블리에 두었습니다. 에디터 도구뿐 아니라 게임 중에 도는
    /// <see cref="TerrainChunkCuller"/> 도 같은 값을 봐야 하기 때문입니다.
    /// </summary>
    [CreateAssetMenu(fileName = "CarDriveWorldSettings", menuName = "CarDrive/월드 설정")]
    public class CarDriveWorldSettings : ScriptableObject
    {
        // --- Constants ---

        /// <summary>Resources 에서 찾을 이름입니다.</summary>
        public const string ResourceName = "CarDriveWorldSettings";

        // --- 풀 심기 ---

        /// <summary>격자 한 칸에 심을 최대 포기 수입니다.</summary>
        [Header("풀 심기")]
        [Tooltip("격자 한 칸(약 0.39m)에 심을 최대 포기 수. " +
                 "드로우 콜은 잎 수가 아니라 '포기 수'에 정비례합니다. " +
                 "Unity 터레인 디테일은 드로우 콜 하나에 약 500개까지만 담기 때문입니다. " +
                 "촘촘하게 하고 싶으면 이 값이 아니라 종의 '포기당 잎 수'를 올리세요. " +
                 "1이면 종의 비중이 곧 '그 종이 차지할 칸의 비율'이 됩니다.")]
        [Range(1, 10)]
        public int maxPerCell = 1;

        /// <summary>
        /// 밀도 배율입니다. <b>포기 수에 그대로 곱해집니다.</b>
        ///
        /// 이 값이 이 시스템에서 가장 잘 듣는 손잡이입니다. 그리기 횟수와 삼각형이
        /// <b>함께</b> 줄기 때문입니다. (거리를 줄이면 가까운 곳의 부담은 그대로입니다)
        ///
        /// <b>잎 폭과 짝입니다.</b> 0.85에서 0.55로 내리면서 종의
        /// <see cref="VegetationSpecies.bladeWidth"/>를 약 1.6배로 넓혔습니다.
        /// 포기가 35% 줄어든 만큼 잎 하나가 넓어져 <b>덮이는 넓이는 그대로</b>입니다.
        /// 잎은 삼각형 한 장이라 넓혀도 삼각형이 늘지 않습니다. 밑변의 두 꼭짓점이
        /// 벌어질 뿐이므로 <b>넓히는 쪽은 공짜</b>입니다.
        ///
        /// 그래서 이 값을 다시 만질 때는 잎 폭도 반대 방향으로 함께 움직이세요.
        /// 한쪽만 바꾸면 풀밭이 성겨 보이거나(밀도만 내림) 뭉개져 보입니다(밀도만 올림).
        /// </summary>
        [Tooltip("밀도 배율. 포기 수에 그대로 곱해져 그리기 횟수와 삼각형이 함께 줄어듭니다. " +
                 "종의 bladeWidth 와 짝입니다 — 이 값을 내리면 잎 폭을 반대로 넓혀야 " +
                 "덮이는 넓이가 유지됩니다. 잎을 넓히는 것은 삼각형이 늘지 않아 공짜입니다.")]
        [Range(0.1f, 1f)]
        public float detailDensity = 0.55f;

        /// <summary>풀을 그리는 최대 거리(m)입니다.</summary>
        [Tooltip("풀을 그리는 최대 거리(m).")]
        [Range(20f, 150f)]
        public float detailDistance = 70f;

        /// <summary>잔디 가중치가 이보다 낮으면 심지 않습니다.</summary>
        [Tooltip("잔디 가중치가 이보다 낮으면 심지 않습니다. 높이 잡으면 풀밭이 흙으로 바뀌는 자리가 칼로 자른 듯 끊깁니다.")]
        [Range(0.1f, 0.9f)]
        public float grassThreshold = 0.4f;

        /// <summary>포기 하나에 세울 잎의 수입니다.</summary>
        [Tooltip("포기 하나에 세울 잎의 수. 잎 하나가 삼각형 한 장입니다. " +
                 "촘촘하게 하려면 여기를 올리세요. 잎이 늘어도 포기 수는 그대로라 " +
                 "드로우 콜이 늘지 않습니다. 삼각형만 늘어나는데 이 게임은 CPU 바운드라 그쪽은 여유가 있습니다.")]
        [Range(2, 32)]
        public int bladesPerTuft = 18;

        /// <summary>한 포기가 퍼지는 반경(m)입니다.</summary>
        [Tooltip("한 포기가 퍼지는 반경(m). 잎을 많이 담을수록 넓게 퍼뜨려야 뭉치지 않습니다.")]
        [Range(0.05f, 0.8f)]
        public float tuftRadius = 0.32f;

        /// <summary>잎의 키(m)입니다.</summary>
        [Tooltip("잎의 키(m).")]
        [Range(0.1f, 2f)]
        public float bladeHeight = 0.55f;

        // --- 식생 종 ---

        /// <summary>
        /// 지면에 심을 식생 종들입니다. <b>비워 두면 위의 값으로 기본 세 종을 만듭니다.</b>
        ///
        /// 예전에는 월드 전체가 풀 한 종류였습니다. 지형은 넓은데 눈에 들어오는 것이
        /// 한 가지뿐이라 어디를 가도 같은 곳처럼 보였습니다.
        ///
        /// <b>포기 수는 늘지 않습니다.</b> <see cref="maxPerCell"/>을 종의 비중대로 나눠 심으므로,
        /// 종을 늘려도 총량은 그대로입니다. 대신 잎 수가 적은 종은 오히려 싸집니다.
        /// 각 종은 경사·고도·군집 규칙을 따로 가집니다.
        /// </summary>
        [Header("식생 종 (비워 두면 기본 3종)")]
        [Tooltip("지면에 심을 식생 종들. 비워 두면 위의 잎 수·반경·키로 기본 3종을 만듭니다. " +
                 "칸당 포기 수는 종의 비중대로 나뉘므로 총량은 늘지 않습니다.")]
        public List<VegetationSpecies> vegetation = new List<VegetationSpecies>();

        // --- 풀 그리기 ---

        /// <summary>이 거리까지는 그라데이션이 온전히 남습니다.</summary>
        [Header("풀 그리기")]
        [Tooltip("이 거리(m)까지는 위에서 빛을 받는 그라데이션이 온전히 남습니다.")]
        public float gradientNear = 10f;

        /// <summary>이 거리부터 단색이 됩니다.</summary>
        [Tooltip("이 거리(m)부터 단색이 됩니다. 멀리서 명암이 남으면 부피가 아니라 잡음으로 보입니다.")]
        public float gradientFar = 30f;

        // --- 밟힘 ---

        /// <summary>얼마나 완전히 눕는지입니다.</summary>
        [Header("밟힘")]
        [Tooltip("얼마나 완전히 눕는지. 1보다 낮추면 차 밑에 풀이 남아 실내로 올라옵니다.")]
        [Range(0f, 1f)]
        public float pushLay = 1f;

        /// <summary>바깥으로 밀리는 거리(m)입니다.</summary>
        [Tooltip("밟힌 풀이 바깥으로 밀리는 거리(m).")]
        [Range(0f, 1f)]
        public float pushSpread = 0.35f;

        /// <summary>위아래로 닿는 높이(m)입니다.</summary>
        [Tooltip("위아래로 이 높이(m)보다 떨어져 있으면 누르지 않습니다.")]
        [Range(0.2f, 8f)]
        public float pushHeightReach = 2f;

        // --- 누르개 배선 ---

        /// <summary>바퀴 하나가 누르는 반경(m)입니다.</summary>
        [Header("누르개 배선")]
        [Tooltip("바퀴 하나가 누르는 반경(m).")]
        public float wheelRadius = 1.2f;

        /// <summary>차체가 누르는 반경(m)입니다.</summary>
        [Tooltip("차체가 누르는 반경(m). 바퀴 넷 사이의 빈 가운데를 덮어야 풀이 실내로 올라오지 않습니다.")]
        public float bodyRadius = 2f;

        /// <summary>사람이 누르는 반경(m)입니다.</summary>
        [Tooltip("걸어 다니는 사람이 누르는 반경(m).")]
        public float playerRadius = 0.5f;

        /// <summary>유령이 누르는 반경(m)입니다.</summary>
        [Tooltip("유령이 누르는 반경(m). 유령은 자국을 남기지 않습니다.")]
        public float ghostRadius = 0.6f;

        /// <summary>사람의 무게(kg)입니다.</summary>
        [Tooltip("사람의 무게(kg). 자국이 남는 시간이 여기서 나옵니다.")]
        public float playerMass = 70f;

        // --- 청크 컬링 ---

        /// <summary>
        /// 이 거리를 넘는 타일은 나무와 풀을 접습니다.
        ///
        /// <b>나무와 풀은 함께 꺼집니다.</b> 유니티의 <c>drawTreesAndFoliage</c> 가 하나뿐이라
        /// 둘을 나눌 수 없습니다. 그래서 이 값이 나무 그리기 거리보다 짧으면
        /// <b>아직 보여야 할 나무가 타일 단위로 사라집니다.</b>
        ///
        /// 실제로 95m 로 두었다가 나무가 눈앞에서 통째로 튀어나오는 문제가 있었습니다.
        /// 지금은 <see cref="TerrainChunkCuller"/> 가 이 값과 터레인의 나무 그리기 거리 중
        /// <b>더 큰 쪽</b>을 쓰므로, 이 값을 낮춰도 나무가 잘리지는 않습니다.
        ///
        /// 풀만 줄이고 싶으면 이 값이 아니라 <see cref="detailDistance"/> 를 만지세요.
        /// </summary>
        /// <summary>
        /// 시야 거리와 그리기 거리에 <b>한꺼번에</b> 곱하는 배율입니다.
        ///
        /// 0.5 로 두면 둘 다 반토막이 납니다. 사양이 낮은 기기에서 옵션으로 내주거나,
        /// 거리 때문에 무거운 것인지 가릴 때 씁니다.
        ///
        /// <b>무엇에 걸리는가.</b>
        ///   시야 — 안개 끝, 카메라 파클립, 타일 활성 거리, 나무 그리는 거리
        ///   그리기 — 풀 그리는 거리, 나무·풀 접는 거리, 지면을 늘 켜 둘 거리
        ///
        /// 이 값은 <b>런타임에 곱해집니다.</b> 위의 기준 수치들을 고치지 않으므로
        /// 1 로 되돌리면 원래대로 돌아옵니다. 실행 중에 바꿔도 됩니다.
        ///
        /// 속도 적응형(<see cref="speedLodEnabled"/>)과는 곱해집니다.
        /// 0.5 로 두고 고속으로 달리면 풀 거리가 원래의 0.25 가 됩니다.
        /// </summary>
        [Header("전체 거리 배율")]
        [Tooltip("시야 거리와 그리기 거리에 한꺼번에 곱합니다. 0.5 면 둘 다 반토막입니다. " +
                 "기준 수치를 고치지 않으므로 1 로 되돌리면 원래대로 돌아옵니다.")]
        [Range(0.25f, 1f)]
        public float rangeScale = 1f;

        /// <summary>
        /// 터레인이 끝나는 자리를 <b>안개로 가릴지</b> 여부입니다.
        ///
        /// <b>왜 필요한가.</b> <see cref="WeatherRig"/> 가 안개의 주인인데,
        /// 맑은 날씨에는 <c>RenderSettings.fog</c> 를 <b>아예 끕니다.</b>
        /// 그러면 터레인이 끝나는 자리를 가려 줄 것이 없어, 다가가면 그 자리에서
        /// 지형이 튀어나옵니다. 시야를 줄일수록 그 경계가 가까워져 더 잘 보입니다.
        ///
        /// 켜 두면 <see cref="ViewRangeScaler"/> 가 <b>모자랄 때만</b> 짙기를 올립니다.
        /// 날씨가 이미 더 짙게 했으면 건드리지 않습니다.
        ///
        /// <b>맑은 날의 그림이 조금 달라집니다.</b> 예전에는 안개가 0이었는데
        /// 이제 아주 옅은 안개가 늘 깔립니다. 시야 배율이 1일 때는 340m 에서
        /// 걷히는 정도라 거의 티가 나지 않지만, 그 차이가 싫으면 이 체크를 끄고
        /// 대신 <see cref="rangeScale"/> 을 1 로 두세요. 둘 다 끄면 경계가 보입니다.
        /// </summary>
        [Tooltip("터레인이 끝나는 자리를 안개로 가립니다. 날씨가 정한 짙기가 모자랄 때만 올립니다. " +
                 "끄면 맑은 날씨에서 지형이 끝나는 경계가 그대로 보입니다.")]
        public bool hideDrawDistanceWithFog = true;

        [Header("청크 컬링 (게임 중에도 쓰입니다)")]
        [Tooltip("이 거리(m)를 넘고 화면 밖인 타일은 나무와 풀을 접습니다. " +
                 "거리만으로는 접지 않습니다 — 그쪽은 나무 그리는 거리와 풀 그리는 거리가 맡습니다.")]
        public float foliageDistance = 95f;

        /// <summary>
        /// 화면 밖 타일의 나무·풀을 접을지 여부입니다.
        ///
        /// <b>거리로는 접지 않습니다.</b> 나무는 <c>Terrain.treeDistance</c>, 풀은
        /// <c>Terrain.detailObjectDistance</c> 가 이미 <b>반경 거리</b>로 잘라 냅니다.
        /// 그쪽은 유니티 내부에서 부드럽게 처리되는데, 타일 단위 접기는 <b>하드 스위치</b>라
        /// 한 장 분량이 한꺼번에 나타나고 사라집니다. 같은 일을 두 번 하면서 결과는 더 나빴습니다.
        ///
        /// <b>화면 밖 판정만 남깁니다.</b> 이건 유니티가 대신 해 주지 않는 일입니다 —
        /// 터레인의 나무·디테일 컬링 패스는 터레인마다 돌기 때문에, 화면에 없는 타일에서도
        /// 그 목록을 훑습니다. 타일이 많을수록 그 비용이 쌓입니다.
        ///
        /// 타일을 크게 키우면(장수가 줄면) 이 항목의 이득도 함께 줄어듭니다. 그때는 꺼도 됩니다.
        /// </summary>
        [Tooltip("화면 밖 타일의 나무·풀을 접습니다. 거리로는 접지 않습니다 — " +
                 "그쪽은 나무·풀 그리는 거리가 이미 반경으로 잘라 냅니다. " +
                 "타일을 크게 키워 장수가 줄면 이 항목의 이득도 줄어듭니다.")]
        public bool foldOffscreenFoliage = true;

        /// <summary>
        /// 나무·풀을 접을지 <b>판정</b>하는 주기(초)입니다.
        ///
        /// <b>왜 주기가 생겼는가.</b> 예전에는 매 프레임 판정했고, 그때는 그럴 이유가 있었습니다 —
        /// 판정에 거리가 섞여 있어서 플레이어가 움직이면 결과가 바뀌었기 때문입니다.
        /// 지금 이 판정은 <b>화면 안인가</b> 하나뿐입니다.
        ///
        /// 화면 판정에는 이미 그림자 여유(<see cref="shadowMargin"/>, 55m)가 붙어 있어서
        /// 실제 화면 가장자리보다 훨씬 바깥에서 켜집니다. 그 여유가 있는 한 판정이
        /// 몇 십 밀리초 늦어도 눈에 보이지 않습니다. 반면 <c>TestPlanesAABB</c> 를
        /// 타일 103장에 매 프레임 돌리는 비용은 그대로 듭니다.
        ///
        /// 0으로 두면 예전처럼 매 프레임 판정합니다.
        /// </summary>
        [Tooltip("나무·풀을 접을지 판정하는 주기(초). 0이면 매 프레임입니다. " +
                 "화면 판정에 그림자 여유가 붙어 있어 조금 늦어도 보이지 않습니다.")]
        [Range(0f, 0.5f)]
        public float foliageCheckInterval = 0.1f;

        /// <summary>
        /// 화면 판정에 둘 여유의 <b>하한</b>(m)입니다.
        ///
        /// <b>이 값이 여유를 혼자 정하지 않습니다.</b> 실제로 필요한 여유는 <b>그림자 거리</b>입니다 —
        /// 화면 밖 언덕이 화면 안으로 그림자를 드리울 수 있는 거리가 딱 그만큼이기 때문입니다.
        /// 그보다 좁게 자르면 화면 가장자리에서 그림자가 통째로 사라집니다.
        ///
        /// 그런데 예전에는 이 값이 손으로 적은 55m 하나였고, <b>실제 그림자 거리를 몰랐습니다.</b>
        /// URP 에셋의 그림자 거리(50m)와 우연히 맞아떨어져 있었을 뿐입니다.
        /// 품질을 High Fidelity(150m)로 올리면 여유는 55m 그대로라 그림자가 튀었을 것입니다.
        ///
        /// 지금은 <see cref="ViewDistances.Ladder.ShadowCasterMargin"/> 이
        /// <b>그림자 거리와 이 값 중 큰 쪽</b>을 씁니다. 그래서 이 값은 "그림자가 짧아도

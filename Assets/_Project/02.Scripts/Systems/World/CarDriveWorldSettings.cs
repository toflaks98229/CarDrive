        public static CarDriveWorldSettings Instance
        {
            get
            {
                if (cached != null) return cached;

                cached = Resources.Load<CarDriveWorldSettings>(ResourceName);
                if (cached == null) cached = CreateInstance<CarDriveWorldSettings>();

                return cached;
            }
        }


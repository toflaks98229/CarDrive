        /// </summary>
        [Tooltip("단계가 오르내리는 속도에 두는 간격(km/h). 임계 언저리에서 떨리는 것을 막습니다.")]
        [Range(0f, 30f)]
        public float speedLodHysteresisKmh = 10f;

        /// <summary>
